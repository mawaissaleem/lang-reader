"""Run 10 hard German cases through each installed Ollama model -> docs/llm_comparison.md.

Usage: python scripts/compare_llms.py [model ...]   (default: all models from /api/tags)
"""
import json
import os
import sys
import time

import httpx

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from translators.llm import OLLAMA_URL, build_prompt, generate, is_valid

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "docs", "llm_comparison.md")

# (case, word as in text, base form, sentence, dictionary meanings)
CASES = [
    ("separable verb", "fängt", "anfangen", "Der Film fängt um acht Uhr an.", ["to begin", "to start"]),
    ("noun, article/plural", "Bücher", "Buch", "Ich habe viele Bücher gelesen.", ["book"]),
    ("strong past", "ging", "gehen", "Gestern ging er früh nach Hause.", ["to go", "to walk"]),
    ("reflexive verb", "freue", "sich freuen", "Ich freue mich auf das Wochenende.", ["to be glad", "to look forward to (auf)"]),
    ("adjective", "schwierig", "schwierig", "Das ist eine schwierige Frage.", ["difficult", "hard", "tricky"]),
    ("preposition, case", "mit", "mit", "Sie fährt mit dem Zug zur Arbeit.", ["with", "by (means of transport)"]),
    ("compound noun", "Handschuhe", "Handschuh", "Im Winter trage ich immer Handschuhe.", ["glove"]),
    ("ambiguous word", "Bank", "Bank", "Wir saßen auf der Bank im Park.", ["bench", "bank (financial)"]),
    ("modal verb", "muss", "müssen", "Ich muss heute noch einkaufen gehen.", ["must", "to have to"]),
    ("context-dependent", "Schloss", "Schloss", "Er hat das Schloss an der Tür gewechselt.", ["castle", "palace", "lock"]),
]


def run(model, case):
    _, word, lemma, sentence, meanings = case
    t = time.time()
    try:
        raw = generate(model, build_prompt(word, lemma, sentence, meanings))
    except Exception as e:  # timeouts, connection errors
        return {"raw": f"ERROR: {e}", "secs": time.time() - t, "valid": False}
    secs = time.time() - t
    try:
        valid = is_valid(json.loads(raw))
    except ValueError:
        valid = False
    return {"raw": raw, "secs": secs, "valid": valid}


def pretty(raw):
    try:
        return json.dumps(json.loads(raw), ensure_ascii=False, indent=2)
    except ValueError:
        return raw


def main():
    models = sys.argv[1:] or [m["name"] for m in httpx.get(f"{OLLAMA_URL}/api/tags").json()["models"]]
    results = {}
    for m in models:
        results[m] = []
        for i, c in enumerate(CASES, 1):
            r = run(m, c)
            results[m].append(r)
            print(f"{m} {i}/10 {r['secs']:.1f}s valid={r['valid']}", flush=True)

    md = ["# LLM comparison", "",
          "Same 10 German words (with sentence and hardcoded dictionary meanings) per model. "
          "Valid = parses as JSON and has the schema's required keys with the right types. "
          "Generated by `backend/scripts/compare_llms.py`.", "",
          "| Model | Avg time (s) | Valid JSON |", "|---|---|---|"]
    for m, rs in results.items():
        avg = sum(r["secs"] for r in rs) / len(rs)
        md.append(f"| {m} | {avg:.1f} | {sum(r['valid'] for r in rs)}/{len(rs)} |")
    for i, c in enumerate(CASES):
        md += ["", f"## {i + 1}. {c[0]}: {c[1]}", "", f"Base: `{c[2]}`. Sentence: {c[3]} Meanings: {', '.join(c[4])}"]
        for m, rs in results.items():
            r = rs[i]
            md += ["", f"### {m} ({r['secs']:.1f} s, valid: {'yes' if r['valid'] else 'no'})", "",
                   "```json", pretty(r["raw"]), "```"]
    with open(OUT, "w") as f:
        f.write("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
